package com.ospaulos.vupth.unit.establishment;

import com.ospaulos.vupth.api.establishment.dto.request.EstablishmentQuickCreateRequest;
import com.ospaulos.vupth.api.establishment.dto.response.EstablishmentQuickCreateResponse;
import com.ospaulos.vupth.api.establishment.usecase.QuickCreateEstablishmentUseCase;
import com.ospaulos.vupth.api.user.exception.UserNotFoundException;
import com.ospaulos.vupth.domain.establishment.model.Establishment;
import com.ospaulos.vupth.domain.establishment.repository.EstablishmentRepository;
import com.ospaulos.vupth.domain.owner.model.Owner;
import com.ospaulos.vupth.domain.owner.repository.OwnerRepository;
import com.ospaulos.vupth.domain.user.model.BaseUser;
import com.ospaulos.vupth.domain.user.repository.UserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

/**
 * Unit tests — QuickCreateEstablishmentUseCase
 *
 * Business rules:
 * - Any authenticated user (already CLIENT) can create an establishment.
 * - OWNER role is automatically added the first time they create one.
 * - If already OWNER, role is not duplicated and userRepository.save is not called.
 * - Establishment ID is a UUID generated by the DB — fixed and immutable.
 * - CLIENT role is always preserved alongside OWNER.
 *
 * Role flow:
 *   Every user born → CLIENT
 *   POST /establishment/quick-create → adds OWNER (if not already)
 *
 * @since v9  extracted from QuickCreateUseCasesTest
 */
@ExtendWith(MockitoExtension.class)
@DisplayName("QuickCreateEstablishmentUseCase")
class QuickCreateEstablishmentUseCaseTest {

    private static final UUID USER_ID  = UUID.randomUUID();
    private static final UUID ESTAB_ID = UUID.randomUUID();

    @Mock UserRepository          userRepository;
    @Mock OwnerRepository         ownerRepository;
    @Mock EstablishmentRepository establishmentRepository;

    @InjectMocks QuickCreateEstablishmentUseCase useCase;

    private BaseUser    user;
    private Establishment establishment;

    @BeforeEach
    void setUp() {
        user = new BaseUser();
        user.setId(USER_ID);
        user.setEmail("user@example.com");
        user.setPassword("$2a$hash");
        user.addClientProfile(); // every user is born CLIENT

        establishment = new Establishment();
        establishment.setId(ESTAB_ID);
        establishment.setName("Test Barbershop");
    }

    // ─────────────────────────────────────────────────────────────
    // Happy path
    // ─────────────────────────────────────────────────────────────

    @Test
    @DisplayName("success: OWNER role added, establishment created with correct id and name")
    void execute_success_addsOwnerRoleAndCreatesEstablishment() {
        assertThat(user.isOwner()).isFalse();

        when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
        when(userRepository.save(any())).thenReturn(user);

        Owner owner = new Owner(user);
        when(ownerRepository.findById(USER_ID)).thenReturn(Optional.of(owner));

        Establishment saved = new Establishment();
        saved.setId(ESTAB_ID);
        saved.setName("Test Barbershop");
        saved.setOwner(owner);
        when(establishmentRepository.save(any())).thenReturn(saved);

        EstablishmentQuickCreateResponse result = useCase.execute(USER_ID,
                new EstablishmentQuickCreateRequest("Test Barbershop"));

        assertThat(result).isNotNull();
        assertThat(result.id()).isEqualTo(ESTAB_ID);
        assertThat(result.name()).isEqualTo("Test Barbershop");
        assertThat(user.isOwner()).isTrue();
        assertThat(user.isClient()).isTrue(); // CLIENT role preserved alongside OWNER
        verify(establishmentRepository).save(any(Establishment.class));
    }

    @Test
    @DisplayName("already OWNER: role not duplicated, userRepository.save not called")
    void execute_alreadyOwner_doesNotDuplicateRole() {
        user.addOwnerProfile();
        assertThat(user.isOwner()).isTrue();

        Owner owner = new Owner(user);
        when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
        when(ownerRepository.findById(USER_ID)).thenReturn(Optional.of(owner));

        Establishment saved = new Establishment();
        saved.setId(ESTAB_ID);
        saved.setName("Second Establishment");
        saved.setOwner(owner);
        when(establishmentRepository.save(any())).thenReturn(saved);

        EstablishmentQuickCreateResponse result = useCase.execute(USER_ID,
                new EstablishmentQuickCreateRequest("Second Establishment"));

        assertThat(result).isNotNull();
        verify(userRepository, never()).save(any()); // role already exists — no redundant save
    }

    @Test
    @DisplayName("CLIENT role always preserved after becoming OWNER")
    void execute_clientRolePreservedAfterOwnerAdded() {
        when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
        when(userRepository.save(any())).thenReturn(user);

        Owner owner = new Owner(user);
        when(ownerRepository.findById(USER_ID)).thenReturn(Optional.of(owner));

        Establishment saved = new Establishment();
        saved.setId(ESTAB_ID);
        saved.setOwner(owner);
        when(establishmentRepository.save(any())).thenReturn(saved);

        useCase.execute(USER_ID, new EstablishmentQuickCreateRequest("Barbearia"));

        assertThat(user.isClient()).isTrue();
        assertThat(user.isOwner()).isTrue();
    }

    // ─────────────────────────────────────────────────────────────
    // Error cases
    // ─────────────────────────────────────────────────────────────

    @Test
    @DisplayName("user not found → throws UserNotFoundException, establishment not saved")
    void execute_userNotFound_throws() {
        when(userRepository.findById(USER_ID)).thenReturn(Optional.empty());

        assertThatThrownBy(() ->
                useCase.execute(USER_ID, new EstablishmentQuickCreateRequest("Name")))
                .isInstanceOf(UserNotFoundException.class);

        verify(establishmentRepository, never()).save(any());
        verify(ownerRepository, never()).findById(any());
    }
}
