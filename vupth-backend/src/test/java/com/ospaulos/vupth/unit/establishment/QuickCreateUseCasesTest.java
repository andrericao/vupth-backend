/**
 * Unit tests — QuickCreateEstablishmentUseCase and QuickCreateProfessionalUseCase
 *
 * QuickCreateEstablishmentUseCase rules:
 * - Any authenticated user (already CLIENT) can create an establishment
 * - OWNER role is automatically added if not already present
 * - Owner profile is created alongside the role
 * - Establishment born with ACTIVE status
 * - Establishment ID is a UUID generated by the DB, fixed and immutable
 *
 * QuickCreateProfessionalUseCase rules:
 * - Any authenticated user can affiliate as a professional
 * - PROFESSIONAL role is automatically added
 * - Professional.id == BaseUser.id (MapsId) — fixed and immutable
 * - User already PROFESSIONAL → UserAlreadyProfessionalException
 * - Establishment must exist → EntityNotFoundException
 * - BaseUser.firstName updated if blank
 *
 * Role flow:
 * Every user is born CLIENT. Additional roles via endpoints:
 *   POST /establishment/quick-create → adds OWNER
 *   POST /professional/quick-create  → adds PROFESSIONAL
 * Multiple roles are valid (e.g. CLIENT + OWNER + PROFESSIONAL for solo shop).
 *
 * @since v5
 */
@ExtendWith(MockitoExtension.class)
class QuickCreateUseCasesTest {

    private static final UUID USER_ID  = UUID.randomUUID();
    private static final UUID ESTAB_ID = UUID.randomUUID();

    private BaseUser user;
    private Establishment establishment;

    @BeforeEach
    void setUp() {
        user = new BaseUser();
        user.setId(USER_ID);
        user.setEmail("user@example.com");
        user.setPassword("$2a$hash");
        user.addClientProfile(); // every user is born CLIENT

        establishment = new Establishment();
        establishment.setId(ESTAB_ID);
        establishment.setName("Test Barbershop");
    }

    // ─────────────────────────────────────────────
    // QuickCreateEstablishmentUseCase
    // ─────────────────────────────────────────────

    @Nested
    @DisplayName("QuickCreateEstablishmentUseCase")
    class EstablishmentTests {

        @Mock UserRepository userRepository;
        @Mock OwnerRepository ownerRepository;
        @Mock EstablishmentRepository establishmentRepository;

        @InjectMocks QuickCreateEstablishmentUseCase useCase;

        @Test
        @DisplayName("multi-loja: com 5 lojas em uso o dono nao cria a sexta (OwnerStoreLimitException); nada e salvo")
        void storeLimit() {
            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
            when(ownerRepository.findById(USER_ID)).thenReturn(Optional.of(new Owner(user)));
            when(establishmentRepository.countByOwner_IdAndStatusNotIn(eq(USER_ID), any())).thenReturn(5L);

            org.assertj.core.api.Assertions.assertThatThrownBy(() -> useCase.execute(USER_ID,
                            new EstablishmentQuickCreateRequest("Loja 6", ServiceType.BARBER)))
                    .isInstanceOf(com.ospaulos.vupth.domain.establishment.exception.OwnerStoreLimitException.class)
                    .hasMessageContaining("5");
            verify(establishmentRepository, never()).save(any());
        }

        @Test
        @DisplayName("success: OWNER role added, establishment created")
        void execute_success_addsOwnerRole() {
            assertThat(user.isOwner()).isFalse();

            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
            when(userRepository.save(any())).thenReturn(user);

            Owner owner = new Owner(user);
            when(ownerRepository.findById(USER_ID)).thenReturn(Optional.of(owner));

            Establishment saved = new Establishment();
            saved.setId(ESTAB_ID);
            saved.setName("Test Barbershop");
            saved.setOwner(owner);
            when(establishmentRepository.save(any())).thenReturn(saved);

            EstablishmentQuickCreateResponse result = useCase.execute(USER_ID,
                    new EstablishmentQuickCreateRequest("Test Barbershop", ServiceType.BARBER));

            assertThat(result).isNotNull();
            assertThat(result.id()).isEqualTo(ESTAB_ID);
            assertThat(user.isOwner()).isTrue();
            assertThat(user.isClient()).isTrue(); // CLIENT role preserved
            verify(establishmentRepository).save(any(Establishment.class));
        }

        @Test
        @DisplayName("user already OWNER: role not duplicated, userRepository.save not called")
        void execute_alreadyOwner_doesNotDuplicateRole() {
            user.addOwnerProfile();
            assertThat(user.isOwner()).isTrue();

            Owner owner = new Owner(user);
            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
            when(ownerRepository.findById(USER_ID)).thenReturn(Optional.of(owner));

            Establishment saved = new Establishment();
            saved.setId(ESTAB_ID);
            saved.setName("Second Establishment");
            saved.setOwner(owner);
            when(establishmentRepository.save(any())).thenReturn(saved);

            EstablishmentQuickCreateResponse result = useCase.execute(USER_ID,
                    new EstablishmentQuickCreateRequest("Second Establishment", ServiceType.BARBER));

            assertThat(result).isNotNull();
            verify(userRepository, never()).save(any()); // role already exists — no save
        }

        @Test
        @DisplayName("user not found → throws UserNotFoundException")
        void execute_userNotFound_throws() {
            when(userRepository.findById(USER_ID)).thenReturn(Optional.empty());

            assertThatThrownBy(() ->
                    useCase.execute(USER_ID, new EstablishmentQuickCreateRequest("Name", ServiceType.BARBER)))
                    .isInstanceOf(UserNotFoundException.class);

            verify(establishmentRepository, never()).save(any());
        }
    }

    // ─────────────────────────────────────────────
    // QuickCreateProfessionalUseCase
    // ─────────────────────────────────────────────

    @Nested
    @DisplayName("QuickCreateProfessionalUseCase")
    class ProfessionalTests {

        @Mock UserRepository userRepository;
        @Mock ProfessionalRepository professionalRepository;
        @Mock EstablishmentRepository establishmentRepository;
        @Mock ProfessionalIntervalService intervalService;

        @InjectMocks QuickCreateProfessionalUseCase useCase;

        @Test
        @DisplayName("success: PROFESSIONAL role added, professional.id == user.id (MapsId)")
        void execute_success_addsProfessionalRole() {
            assertThat(user.isProfessional()).isFalse();

            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
            when(userRepository.save(any())).thenReturn(user);
            when(establishmentRepository.findById(ESTAB_ID)).thenReturn(Optional.of(establishment));
            ProfessionalQuickCreateResponse result = useCase.execute(USER_ID,
                    new ProfessionalQuickCreateRequest("Carlos", ESTAB_ID, "Barber"));

            assertThat(result).isNotNull();
            assertThat(user.isProfessional()).isTrue();
            assertThat(user.isClient()).isTrue(); // CLIENT preserved
            verify(userRepository).save(any(BaseUser.class));
        }

        @Test
        @DisplayName("solo shop: OWNER becoming PROFESSIONAL — both roles active")
        void execute_ownerBecomeProfessional_bothRolesActive() {
            user.addOwnerProfile();
            assertThat(user.isOwner()).isTrue();
            assertThat(user.isProfessional()).isFalse();

            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
            when(userRepository.save(any())).thenReturn(user);
            when(establishmentRepository.findById(ESTAB_ID)).thenReturn(Optional.of(establishment));
            useCase.execute(USER_ID, new ProfessionalQuickCreateRequest("Carlos", ESTAB_ID, null));

            // After execution: CLIENT + OWNER + PROFESSIONAL
            assertThat(user.isClient()).isTrue();
            assertThat(user.isOwner()).isTrue();
            assertThat(user.isProfessional()).isTrue();
        }

        @Test
        @DisplayName("user already PROFESSIONAL → throws UserAlreadyProfessionalException")
        void execute_alreadyProfessional_throws() {
            user.addRole(RoleType.PROFESSIONAL);
            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));

            assertThatThrownBy(() ->
                    useCase.execute(USER_ID, new ProfessionalQuickCreateRequest("Carlos", ESTAB_ID, null)))
                    .isInstanceOf(UserAlreadyProfessionalException.class);

            verify(professionalRepository, never()).save(any());
        }

        @Test
        @DisplayName("user not found → throws UserNotFoundException")
        void execute_userNotFound_throws() {
            when(userRepository.findById(USER_ID)).thenReturn(Optional.empty());

            assertThatThrownBy(() ->
                    useCase.execute(USER_ID, new ProfessionalQuickCreateRequest("Carlos", ESTAB_ID, null)))
                    .isInstanceOf(UserNotFoundException.class);
        }

        @Test
        @DisplayName("blank firstName updated in BaseUser")
        void execute_updatesNameIfBlank() {
            user.setFirstName(null);

            when(userRepository.findById(USER_ID)).thenReturn(Optional.of(user));
            when(userRepository.save(any())).thenReturn(user);
            when(establishmentRepository.findById(ESTAB_ID)).thenReturn(Optional.of(establishment));
            useCase.execute(USER_ID, new ProfessionalQuickCreateRequest("Carlos Silva", ESTAB_ID, null));

            assertThat(user.getFirstName()).isEqualTo("Carlos Silva");
        }
    }
}
